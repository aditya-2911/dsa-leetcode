class Solution:
    def countCommas(self, n: int) -> int:
        total=0

        if n<=999999:
            total+=max(n-999,0)
        if n>999999 and n<=999999999:
            total+=(999999-999)+(n-999999)*2
        if n>999999999 and n<=999999999999:
            total+=(999999-999)+(999999999-999999)*2+(n-999999999)*3
        if n>999999999999 and n<=999999999999999:
             total+=(999999-999)+(999999999-999999)*2+(999999999999-999999999)*3+(n-999999999999)*4
        if n>999999999999999:
            total+=(999999-999)+(999999999-999999)*2+(999999999999-999999999)*3+(999999999999999-999999999999)*4+(n-999999999999999)*5
        
        return total